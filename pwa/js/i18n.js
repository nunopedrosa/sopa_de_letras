// Look up a key in the active language, falling back to Portuguese,
// then to the raw key. {placeholders} are replaced from params.
export function t(key, params) {
  let s = (STRINGS[lang] && STRINGS[lang][key]) ?? STRINGS.pt[key] ?? key;
  if (params) for (const [k, v] of Object.entries(params)) s = s.replaceAll(`{${k}}`, v);
  return s;
}

// Translate static markup: elements with data-i18n (textContent),
// data-i18n-ph (placeholder), data-i18n-title (title attr).
export function applyStaticTranslations(root = document) {
  for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll('[data-i18n-ph]')) el.placeholder = t(el.dataset.i18nPh);
  for (const el of root.querySelectorAll('[data-i18n-title]')) el.title = t(el.dataset.i18nTitle);
  document.title = t('appTitle');
}
